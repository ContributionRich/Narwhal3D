"""CPython Unicode transcript data generator (not an application fallback).

Python is required to probe the actual interpreter Unicode semantics. Extracted
unchanged from the qualified Unicode generator; only transcript data is emitted.
"""
import sys
import unicodedata

MARKERS = {"command_history": ("// BEGIN GENERATED PY CASE TABLES", "// END GENERATED PY CASE TABLES")}

def _runs(pairs):
    """Merge sorted (codepoint, key) pairs into [lo, hi, key] runs of consecutive
    codepoints sharing a key."""
    out = []
    for cp, key in pairs:
        if out and out[-1][1] == cp - 1 and out[-1][2] == key:
            out[-1][1] = cp
        else:
            out.append([cp, cp, key])
    return out

def _fmt_pairs(name, doc, rows):
    """One entry per line: this is rustfmt's layout, so editor format-on-save leaves the
    block unchanged and --check stays meaningful."""
    lines = [f"/// {doc}", f"const {name}: &[(u32, u32)] = &["]
    lines.extend(f"    (0x{lo:x}, 0x{hi:x})," for lo, hi in rows)
    lines.append("];")
    return "\n".join(lines)

def _is_surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF

def _cased(ch):
    # Unicode Cased = Lowercase + Uppercase + Lt. CPython's islower/isupper implement the
    # Lowercase/Uppercase derived properties (including Other_Lowercase/Other_Uppercase).
    return ch.islower() or ch.isupper() or unicodedata.category(ch) == "Lt"

def _case_ignorable_by_probe(ch):
    """Case_Ignorable as CPython's ``str.lower()`` applies it in the final-sigma rule.

    ``unicodedata`` does not expose the property, so it is measured through the same
    rule. Two probes are needed because a cased ``ch`` is always final in ``"A"+ch+"Σ"``:
    * uncased ch: "A"+ch+"Σ" ends in ς exactly when ch is ignorable (the scan skips it
      to reach the cased A);
    * cased ch: "1"+ch+"Σ" ends in ς exactly when ch is NOT ignorable (ch itself is the
      cased character found by the backward scan). '1' is neither cased nor ignorable."""
    if _cased(ch):
        return not ("1" + ch + "\u03a3").lower().endswith("\u03c2")
    return ("A" + ch + "\u03a3").lower().endswith("\u03c2")

def build_command_history_block():
    # The probes rely on '1' being neither cased nor case-ignorable; check that first.
    assert ("A1\u03a3").lower() == "a1\u03c3"
    lower_rows = []
    cased_pairs = []
    ignorable_pairs = []
    for cp in range(0x110000):
        if _is_surrogate(cp):
            continue
        ch = chr(cp)
        mapped = ch.lower()
        if mapped != ch:
            lower_rows.append((cp, [ord(c) for c in mapped]))
        if _cased(ch):
            cased_pairs.append((cp, 0))
        if _case_ignorable_by_probe(ch):
            ignorable_pairs.append((cp, 0))
    cased_rows = [(lo, hi) for lo, hi, _ in _runs(cased_pairs)]
    ignorable_rows = [(lo, hi) for lo, hi, _ in _runs(ignorable_pairs)]

    parts = [
        MARKERS["command_history"][0],
        f"// Generated by native/ui_core/transcript_unicode.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).",
        "// Do not edit by hand: regenerate and re-splice.",
        "/// Full `str.lower()` mapping (cp, mapped code points) for every non-sigma code point",
        "/// that maps to something other than itself. U+03A3 is listed for documentation; the",
        "/// port resolves it with the final-sigma rule instead.",
        "const PY_LOWER_FULL: &[(u32, &[u32])] = &[",
    ]
    parts.extend(
        f"    (0x{cp:x}, &[{', '.join(f'0x{m:x}' for m in mapped)}])," for cp, mapped in lower_rows)
    parts.append("];")
    parts.append("")
    parts.append(_fmt_pairs(
        "PY_CASED",
        "Code points for which CPython's cased test (Cased property) is true.",
        cased_rows))
    parts.append("")
    parts.append(_fmt_pairs(
        "PY_CASE_IGNORABLE",
        "Case-ignorable code points as CPython's final-sigma rule uses them (cased ones included).",
        ignorable_rows))
    parts.append(MARKERS["command_history"][1])
    return "\n".join(parts) + "\n"
