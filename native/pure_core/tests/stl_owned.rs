#[test]
fn stl_owned_binary_truncation_and_legacy_dialect() {
    let data = encode(&COORDS[..9], true, b"x");
    assert_eq!(size(&data[..80], 1), (-20, [-20, 0, 0]));
    assert_eq!(size(&data[..133], 1), (-21, [-21, 1, 134]));
    let mut solid = data.clone();
    solid[..5].copy_from_slice(b"solid");
    assert_eq!(size(&solid, 0).0, 0); // exact legacy file API detection
    assert_eq!(decode(&solid, 1), COORDS[..9]);
    for prefix in [b"\x0bsolid".as_slice(), b"solidarity", b" \t\r\nsolid"] {
        assert_eq!(size(prefix, 0).0, 0);
    }
    assert_eq!(size(b"SOLID", 0).0, -20); // case-sensitive
    assert_eq!(size(b"\xa0solid", 0).0, -20); // bytes.lstrip, not str.strip
}

#[test]
fn stl_owned_checked_spans_and_exact_output_capacities() {
    let data = encode(&COORDS[..9], true, b"x");
    let mut diag = [0; 3];
    unsafe {
        assert_eq!(
            narwhal_pure_core_stl_file_size(std::ptr::null(), 1, 0, diag.as_mut_ptr()),
            -1
        );
        assert_eq!(
            narwhal_pure_core_stl_file_size(data.as_ptr(), usize::MAX, 0, diag.as_mut_ptr()),
            -1
        );
        assert_eq!(
            narwhal_pure_core_stl_file_size(data.as_ptr(), data.len(), 0, std::ptr::null_mut()),
            -1
        );
        assert_eq!(
            narwhal_pure_core_stl_file_size(data.as_ptr(), data.len(), 4, diag.as_mut_ptr()),
            -2
        );
        let mut out = [77.; 10];
        assert_eq!(
            narwhal_pure_core_stl_file_decode(data.as_ptr(), data.len(), 0, out.as_mut_ptr(), 8),
            -3
        );
        assert_eq!(out, [77.; 10]);
        assert_eq!(
            narwhal_pure_core_stl_file_decode(data.as_ptr(), data.len(), 0, out.as_mut_ptr(), 10),
            -3
        );
        assert_eq!(out, [77.; 10]);
        assert_eq!(
            narwhal_pure_core_stl_file_decode(
                data.as_ptr(),
                data.len(),
                0,
                std::ptr::null_mut(),
                9
            ),
            -1
        );
    }
}

