fn encode(coords: &[f64], binary: bool, name: &[u8]) -> Vec<u8> {
    let count = coords.len() / 9;
    unsafe {
        let size = narwhal_pure_core_stl_size_owned(
            coords.as_ptr(),
            count,
            name.as_ptr(),
            name.len(),
            binary as u8,
        );
        assert!(size >= 0, "size={size}");
        let mut out = vec![0; size as usize];
        assert_eq!(
            narwhal_pure_core_stl_encode_owned(
                coords.as_ptr(),
                count,
                name.as_ptr(),
                name.len(),
                binary as u8,
                out.as_mut_ptr(),
                out.len()
            ),
            0
        );
        out
    }
}
fn size(data: &[u8], mode: u8) -> (i64, [i64; 3]) {
    let mut diagnostic = [0; 3];
    let n = unsafe {
        narwhal_pure_core_stl_file_size(data.as_ptr(), data.len(), mode, diagnostic.as_mut_ptr())
    };
    (n, diagnostic)
}
fn decode(data: &[u8], mode: u8) -> Vec<f64> {
    let (n, diag) = size(data, mode);
    assert!(n >= 0, "{diag:?}");
    let mut out = vec![0.; n as usize];
    assert_eq!(
        unsafe {
            narwhal_pure_core_stl_file_decode(
                data.as_ptr(),
                data.len(),
                mode,
                out.as_mut_ptr(),
                out.len(),
            )
        },
        0
    );
    out
}

#[test]
fn stl_owned_independent_ascii_and_binary_capture() {
    assert_eq!(encode(COORDS, false, b"\xe9 golden"), ASCII_GOLDEN);
    let binary: Vec<u8> = BINARY_HEX
        .as_bytes()
        .chunks_exact(2)
        .map(|b| u8::from_str_radix(std::str::from_utf8(b).unwrap(), 16).unwrap())
        .collect();
    assert_eq!(encode(COORDS, true, b"\xe9 golden"), binary);
    let got = decode(&binary, 0);
    for (a, b) in got.iter().zip(COORDS) {
        assert_eq!(*a, *b as f32 as f64);
    }
    let got = decode(ASCII_GOLDEN, 0);
    for (a, b) in got.iter().zip(COORDS) {
        assert!((a - b).abs() <= 1e-8 * b.abs().max(1.));
    }
}

