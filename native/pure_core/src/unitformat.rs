// Additive C ABI exports; checked by source and package semantic probes.
//
// The Python adapter owns the parts the reference does with Python types: the
// value's numeric coercion, the mode name's `str` handling and the exception
// TYPE and MESSAGE for a bad mode / precision. Rust owns the pure computation:
// mode normalisation, precision range validation, rounding, reduction and
// string building, honouring the caller's decimal-context precision.
//
// Two exports. `resolve_mode` returns the normalized mode (and, for the
// unsupported case, the offending text so the adapter can build the exact
// reference message). `format` takes an already-resolved mode and a raw
// precision and returns the rendered string plus an error code, writing into a
// caller-owned buffer (two-pass: a too-small buffer is reported via `needed` and
// `return 1`, never written).
//
// Error codes (the `format` export returns one of these; `resolve_mode` returns
// the mode category 0/1/2 or `UF_UNSUPPORTED`):
const UF_OK: i32 = 0;
const UF_DECIMAL: i32 = 0; // mode category: Decimal
const UF_FRACTIONAL: i32 = 1; // mode category: Fractional
const UF_FEET_INCH: i32 = 2; // mode category: FeetInch
const UF_PRECISION_RANGE: i32 = 10; // `PrecisionOutOfRange` -> ValueError
const UF_NAN: i32 = 11; // `NanNotConvertible`    -> ValueError
const UF_INVALID_OP: i32 = 12; // `InvalidOperation`     -> decimal.InvalidOperation
const UF_UNSUPPORTED: i32 = 13; // `UnsupportedMode`      -> ValueError
const UF_SHORT_BUFFER: i32 = 14; // `format`: grow the output buffer and retry

/// Explicit bounded limit on the mode-name span (1 MiB): a mode name longer than this
/// is refused as unsupported. The reference (which `str.strip()`s) would accept an
/// arbitrarily long whitespace-padded name, so this is a DOCUMENTED explicit limit, not
/// exact parity; it bounds the O(n) normalization work with no unbounded allocation.
const MAX_MODE: usize = 1024 * 1024;

/// Resolve a display-mode name (UTF-8, caller-owned) to a stable code. Returns
/// `UF_DECIMAL` (0), `UF_FRACTIONAL` (1) or `UF_FEET_INCH` (2) on success, or
/// `UF_UNSUPPORTED` (13) when the name is not a known mode. The adapter owns the
/// unsupported-mode exception message (the reference renders `{mode!r}` of the
/// ORIGINAL argument, which the adapter holds). Mode normalisation itself
/// (`str.strip()`, lowercase, `&`->`and`) is Rust's job.
/// # Safety
/// `input` must reference `length` initialized bytes.
#[no_mangle]
pub unsafe extern "C" fn narwhal_pure_core_unitformat_resolve_mode(
    input: *const u8,
    length: usize,
) -> i32 {
    if length > MAX_MODE {
        return UF_UNSUPPORTED;
    }
    let Some(bytes) = (unsafe { crate::checked_slice(input, length) }) else {
        return UF_UNSUPPORTED;
    };
    let Ok(text) = std::str::from_utf8(bytes) else {
        return UF_UNSUPPORTED;
    };
    match parse_mode(text) {
        Ok(DisplayMode::Decimal) => UF_DECIMAL,
        Ok(DisplayMode::Fractional) => UF_FRACTIONAL,
        Ok(DisplayMode::FeetInch) => UF_FEET_INCH,
        Err(_) => UF_UNSUPPORTED,
    }
}

/// Format a coerced value for a resolved mode and a raw precision, writing the
/// rendered string into the caller-owned `out` buffer. Returns `UF_OK` on
/// success (writing exactly `needed[0]` bytes), or one of the error codes above.
/// A buffer too small for the result reports the required size in `needed[0]`
/// and returns UF_SHORT_BUFFER (no partial write), so the adapter can grow and retry.
/// # Safety
/// `out` must reference `out_cap` writable bytes; `needed` a writable usize.
#[no_mangle]
pub unsafe extern "C" fn narwhal_pure_core_unitformat_format(
    value: f64,
    mode: u32,
    precision: i64,
    context_precision: u32,
    out: *mut u8,
    out_cap: usize,
    needed: *mut usize,
) -> i32 {
    let Some(needed) = (unsafe { crate::checked_slice_mut(needed, 1) }) else {
        return UF_INVALID_OP;
    };
    let mode = match mode {
        0 => DisplayMode::Decimal,
        1 => DisplayMode::Fractional,
        2 => DisplayMode::FeetInch,
        _ => return UF_UNSUPPORTED,
    };
    let result = format_checked_with_context(value, mode, precision, context_precision as usize);
    let (code, rendered) = match result {
        Ok(s) => (UF_OK, s),
        Err(UnitFormatError::PrecisionOutOfRange { .. }) => (UF_PRECISION_RANGE, String::new()),
        Err(UnitFormatError::NanNotConvertible) => (UF_NAN, String::new()),
        Err(UnitFormatError::InvalidOperation) => (UF_INVALID_OP, String::new()),
        Err(UnitFormatError::UnsupportedMode(_)) => (UF_UNSUPPORTED, String::new()),
    };
    if code != UF_OK {
        needed[0] = 0;
        return code;
    }
    let bytes = rendered.as_bytes();
    if bytes.len() > out_cap {
        needed[0] = bytes.len();
        return UF_SHORT_BUFFER;
    }
    let Some(dst) = (unsafe { crate::checked_slice_mut(out, out_cap) }) else {
        return UF_UNSUPPORTED;
    };
    dst[..bytes.len()].copy_from_slice(bytes);
    needed[0] = bytes.len();
    UF_OK
}

