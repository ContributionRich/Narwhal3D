/// Display mode, after name normalisation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DisplayMode {
    Decimal,
    Fractional,
    FeetInch,
}

/// The reference's error classes, one variant each.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UnitFormatError {
    /// `ValueError: unsupported display mode ...` (carries the offending text).
    UnsupportedMode(String),
    /// `ValueError` for precision outside the mode's range.
    PrecisionOutOfRange { mode: DisplayMode, value: i64 },
    /// `ValueError: cannot convert NaN to integer` (fractional and feet-and-inches only).
    NanNotConvertible,
    /// `decimal.InvalidOperation`: an infinity, or a result longer than 28 digits.
    InvalidOperation,
}

/// Decimal context precision used by the reference (the default).
const CONTEXT_PRECISION: usize = 28;

/// Map a display-mode name to its mode, as the reference's `_norm_mode` does.
pub fn parse_mode(mode: &str) -> Result<DisplayMode, UnitFormatError> {
    let stripped = py_strip(mode);
    let mut normalized = String::with_capacity(stripped.len());
    for c in stripped.chars() {
        if c == '&' {
            normalized.push_str("and");
        } else if c.is_ascii() {
            normalized.push(c.to_ascii_lowercase());
        } else {
            normalized.push(c);
        }
    }
    match normalized.as_str() {
        "decimal" => Ok(DisplayMode::Decimal),
        "fractional" | "fraction" => Ok(DisplayMode::Fractional),
        "feet and inches" | "feet_inches" | "feet-inch" => Ok(DisplayMode::FeetInch),
        _ => Err(UnitFormatError::UnsupportedMode(mode.to_string())),
    }
}

/// Format a length given in model units. Validation order matches the reference: mode, then
/// precision, then the value's own rules.
pub fn format_length(value: f64, mode: &str, precision: i64) -> Result<String, UnitFormatError> {
    format_checked(value, parse_mode(mode)?, precision)
}

/// Format an already-coerced value for an already-parsed mode and a raw precision, honoring an
/// explicit decimal-context precision. The reference reads the thread's `decimal` context
/// (default 28); the adapter passes that value through so the coefficient digit-limit matches
/// whatever context the caller is running under. Validation order: precision, then the value.
pub fn format_checked_with_context(
    value: f64,
    mode: DisplayMode,
    precision: i64,
    context_precision: usize,
) -> Result<String, UnitFormatError> {
    match mode {
        DisplayMode::Decimal => format_decimal(
            value,
            checked_range(mode, precision, 0, 12)?,
            context_precision,
        ),
        DisplayMode::Fractional => format_fractional(
            value,
            checked_range(mode, precision, 1, 1024)?,
            context_precision,
        ),
        DisplayMode::FeetInch => format_feet_inch(
            value,
            checked_range(mode, precision, 1, 1024)?,
            context_precision,
        ),
    }
}

/// Format an already-coerced value for an already-parsed mode and a raw precision. This is the
/// seam the Python adapter calls after it has converted the value with `float()`, normalised the
/// mode and converted the precision with `int()`. Pins the decimal context to the default 28.
pub fn format_checked(
    value: f64,
    mode: DisplayMode,
    precision: i64,
) -> Result<String, UnitFormatError> {
    format_checked_with_context(value, mode, precision, CONTEXT_PRECISION)
}

fn checked_range(mode: DisplayMode, value: i64, lo: i64, hi: i64) -> Result<u32, UnitFormatError> {
    if (lo..=hi).contains(&value) {
        Ok(value as u32)
    } else {
        Err(UnitFormatError::PrecisionOutOfRange { mode, value })
    }
}

fn format_decimal(value: f64, places: u32, ctx: usize) -> Result<String, UnitFormatError> {
    if value.is_nan() {
        return Ok("NaN".to_string());
    }
    if value.is_infinite() {
        return Err(UnitFormatError::InvalidOperation);
    }
    let negative = value < 0.0;
    let (digits, exp) = shortest_decimal(value.abs());
    let coefficient = scaled_integer(&digits, exp, 1, places as i32);
    if coefficient.len() > ctx {
        return Err(UnitFormatError::InvalidOperation);
    }
    let body = fixed_point(&coefficient, places as usize);
    Ok(if negative { format!("-{body}") } else { body })
}

fn format_fractional(value: f64, denom: u32, ctx: usize) -> Result<String, UnitFormatError> {
    let (negative, num) = scaled_numerator(value, denom, ctx)?;
    // Decimal long division by the small denominator: no fixed-width fold of `num`.
    let (whole, rem) = div_small(&num, denom);
    let body = if rem == 0 {
        digits_to_string(&whole)
    } else {
        let g = gcd(rem, denom);
        if whole.as_slice() != [0] {
            format!("{}-{}/{}", digits_to_string(&whole), rem / g, denom / g)
        } else {
            format!("{}/{}", rem / g, denom / g)
        }
    };
    Ok(if negative { format!("-{body}") } else { body })
}

fn format_feet_inch(value: f64, denom: u32, ctx: usize) -> Result<String, UnitFormatError> {
    let (negative, num) = scaled_numerator(value, denom, ctx)?;
    // Decimal long division by `12 * denom` (<= 12288): `feet` may be hundreds of digits
    // for a large value, so it stays a digit string; the inch part is small (u32).
    let (feet_digits, inch_num) = div_small(&num, 12 * denom);
    let inch_whole = inch_num / denom;
    let inch_rem = inch_num % denom;
    let inch_part = if inch_rem == 0 {
        inch_whole.to_string()
    } else {
        let g = gcd(inch_rem, denom);
        if inch_whole != 0 {
            format!("{inch_whole} {}/{}", inch_rem / g, denom / g)
        } else {
            format!("{}/{}", inch_rem / g, denom / g)
        }
    };
    let body = if feet_digits.as_slice() != [0] {
        format!("{}'-{}\"", digits_to_string(&feet_digits), inch_part)
    } else {
        format!("{inch_part}\"")
    };
    Ok(if negative { format!("-{body}") } else { body })
}

/// `int((Decimal(str(|value|)) * denom).quantize(1, ROUND_HALF_UP))` as the reference
/// computes it: an infinity fails quantize, NaN fails `int()`, and a coefficient longer
/// than the caller's context precision fails quantize.
///
/// The reference's multiply `Decimal(str(mag)) * denom` is a **context operation** rounded
/// to `prec` significant digits using the context's rounding mode (default HALF_EVEN). The
/// subsequent `.quantize(1, HALF_UP)` then rounds to integer with an explicit HALF_UP
/// (which overrides the context rounding). This function reproduces that two-step rounding:
/// first HALF_EVEN to `ctx` sig digits, then HALF_UP to integer.
///
/// The result is the scaled numerator as big-endian decimal DIGITS (never a fixed-width
/// integer), so large values under a large context precision cannot overflow or wrap across
/// the C ABI.
fn scaled_numerator(
    value: f64,
    denom: u32,
    ctx: usize,
) -> Result<(bool, Vec<u8>), UnitFormatError> {
    if value.is_nan() {
        return Err(UnitFormatError::NanNotConvertible);
    }
    if value.is_infinite() {
        return Err(UnitFormatError::InvalidOperation);
    }
    let negative = value < 0.0;
    let (digits, exp) = shortest_decimal(value.abs());
    let exact = mul_small(&digits, denom);
    // Step 1: round to `ctx` significant digits using HALF_EVEN (the default context
    // rounding for the multiply). If the product already has <= `ctx` sig digits, it is
    // exact and no rounding is needed.
    let (mantissa, shift) = if exact.len() <= ctx {
        (exact, exp)
    } else {
        let rounded = round_sig_half_even(&exact, ctx);
        (rounded, exp + (exact.len() - ctx) as i32)
    };
    // Step 2: round to integer using HALF_UP (the reference's explicit quantize rounding).
    let integer = scaled_integer(&mantissa, shift, 1, 0);
    if integer.len() > ctx {
        return Err(UnitFormatError::InvalidOperation);
    }
    Ok((negative, integer))
}

/// Shortest round-trip decimal of a finite non-negative float, as `(digits, exp)` with
/// value = digits * 10^exp. This is `str(float)` (Python's repr), including the tie rule that
/// prefers the correctly rounded same-length form.
fn shortest_decimal(magnitude: f64) -> (Vec<u8>, i32) {
    if magnitude == 0.0 {
        return (vec![0], 0);
    }
    let shortest = format!("{:e}", magnitude);
    let shortest_mantissa = shortest.split_once('e').expect("`{:e}` has an exponent").0;
    let count = shortest_mantissa.bytes().filter(u8::is_ascii_digit).count();
    let exact = format!("{:.*e}", count - 1, magnitude);
    let chosen = if exact.parse::<f64>() == Ok(magnitude) {
        exact
    } else {
        shortest
    };
    let (mantissa, exponent) = chosen.split_once('e').expect("`{:e}` has an exponent");
    let exponent: i32 = exponent.parse().expect("exponent is an integer");
    let digits: Vec<u8> = mantissa
        .bytes()
        .filter(u8::is_ascii_digit)
        .map(|b| b - b'0')
        .collect();
    let exp = exponent - (digits.len() as i32 - 1);
    (digits, exp)
}

/// `round_half_up(digits * mult * 10^(exp + places))` as big-endian decimal digits with no
/// leading zeros (zero is `[0]`). Ties round up in magnitude, as ROUND_HALF_UP does.
fn scaled_integer(digits: &[u8], exp: i32, mult: u32, places: i32) -> Vec<u8> {
    let product = mul_small(digits, mult);
    let shift = exp + places;
    if shift >= 0 {
        let mut out = product;
        if out != [0] {
            out.extend(std::iter::repeat_n(0, shift as usize));
        }
        return normalize(out);
    }
    let drop = (-shift) as usize;
    if drop > product.len() {
        return vec![0];
    }
    let keep = product.len() - drop;
    let round_digit = product[keep];
    let mut kept = product[..keep].to_vec();
    if round_digit >= 5 {
        kept = increment(kept);
    }
    normalize(kept)
}

fn mul_small(digits: &[u8], multiplier: u32) -> Vec<u8> {
    let mut out = Vec::with_capacity(digits.len() + 10);
    let mut carry: u64 = 0;
    for &d in digits.iter().rev() {
        let v = d as u64 * multiplier as u64 + carry;
        out.push((v % 10) as u8);
        carry = v / 10;
    }
    while carry > 0 {
        out.push((carry % 10) as u8);
        carry /= 10;
    }
    out.reverse();
    normalize(out)
}

fn increment(mut digits: Vec<u8>) -> Vec<u8> {
    for d in digits.iter_mut().rev() {
        if *d == 9 {
            *d = 0;
        } else {
            *d += 1;
            return digits;
        }
    }
    let mut out = vec![1];
    out.extend(digits);
    out
}

fn normalize(digits: Vec<u8>) -> Vec<u8> {
    let first = digits.iter().position(|&d| d != 0);
    match first {
        Some(i) => digits[i..].to_vec(),
        None => vec![0],
    }
}

/// Coefficient digits with `places` decimals, as Decimal's fixed-point `format(q, "f")`.
fn fixed_point(coefficient: &[u8], places: usize) -> String {
    let text: String = coefficient.iter().map(|&d| (b'0' + d) as char).collect();
    if places == 0 {
        return text;
    }
    let padded = if text.len() <= places {
        format!("{}{}", "0".repeat(places + 1 - text.len()), text)
    } else {
        text
    };
    let split = padded.len() - places;
    format!("{}.{}", &padded[..split], &padded[split..])
}

/// Round a big-endian digit string to `prec` significant digits using HALF_EVEN (the
/// default decimal context rounding). If the digit string already has `<= prec` digits,
/// it is returned unchanged. Otherwise the first `prec` digits are kept and the
/// remainder decides the rounding: > 5 rounds up, < 5 rounds down, exactly 5 with no
/// further non-zero digits is a tie resolved to the nearest even last kept digit, and
/// exactly 5 with any further non-zero digit rounds up (away from zero).
fn round_sig_half_even(digits: &[u8], prec: usize) -> Vec<u8> {
    if digits.len() <= prec {
        return digits.to_vec();
    }
    let kept: Vec<u8> = digits[..prec].to_vec();
    let next = digits[prec];
    let rest_all_zero = digits[prec + 1..].iter().all(|&d| d == 0);
    let round_up = next > 5
        || next == 5 && !rest_all_zero
        || next == 5 && kept.last().copied().unwrap_or(0) % 2 == 1;
    if round_up {
        increment(kept)
    } else {
        kept
    }
}

fn gcd(mut a: u32, mut b: u32) -> u32 {
    while b != 0 {
        let t = a % b;
        a = b;
        b = t;
    }
    a
}

/// Decimal long division of a big-endian digit string by a small divisor (<= 12 * 1024,
/// fits u32). Per digit the carry is `< divisor`, so `carry * 10 + digit` < 122889 and the
/// quotient digit is always < 10 -- no overflow path anywhere. Returns the normalized
/// quotient (`[0]` for zero) and the remainder. Bounded: at most one pass over the input.
fn div_small(digits: &[u8], divisor: u32) -> (Vec<u8>, u32) {
    let mut quotient = Vec::with_capacity(digits.len());
    let mut carry = 0u32;
    for &d in digits {
        let current = carry * 10 + d as u32;
        quotient.push((current / divisor) as u8);
        carry = current % divisor;
    }
    (normalize(quotient), carry)
}

fn digits_to_string(digits: &[u8]) -> String {
    digits.iter().map(|&d| (b'0' + d) as char).collect()
}

/// `str.strip()` with no arguments: ASCII whitespace plus the generated Unicode table.
fn py_strip(s: &str) -> &str {
    s.trim_matches(py_is_space)
}

fn py_is_space(c: char) -> bool {
    let cp = c as u32;
    if cp < 0x80 {
        return matches!(cp, 0x09..=0x0d | 0x1c..=0x20);
    }
    in_ranges(PY_SPACE_NON_ASCII, cp)
}

fn in_ranges(table: &[(u32, u32)], cp: u32) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < cp {
                std::cmp::Ordering::Less
            } else if lo > cp {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

