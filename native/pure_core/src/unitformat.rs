//! Port of `narwhal3d/unitformat.py`: how a length is DISPLAYED (status bar, distance commands).
//!
//! Native-only production display formatter, registered and ABI-qualified.
//! This is display formatting only. The model unit is accepted
//! and ignored by the reference, and it is not a unit conversion.
//!
//! Parity notes (reproduced exactly, measured against CPython 3.13 `decimal`):
//! * the reference rounds `Decimal(str(value))` with ROUND_HALF_UP. `str(float)` is the
//!   shortest round-trip repr, so the port works on those shortest digits (including the
//!   half-to-even tie rule of repr), not on the binary value;
//! * **Fractional / Feet-Inch:** the reference computes
//!   `int((Decimal(str(mag)) * denom).quantize(1, HALF_UP))`. The **multiply** is a
//!   context operation rounded to `prec` significant digits using the context's rounding
//!   mode (default **HALF_EVEN**); the **quantize** then rounds to integer with an explicit
//!   `rounding=ROUND_HALF_UP` (which overrides the context rounding). A result coefficient
//!   longer than `prec` raises `InvalidOperation`.
//!   **Scope:** this port emulates the DEFAULT context rounding (HALF_EVEN) for the multiply
//!   step. A non-default context rounding mode is refused by the adapter with `RuntimeError`
//!   (the reference would use the context rounding for the multiply, which this port does
//!   not support). The app never customizes the context (verified: no `localcontext` /
//!   `setcontext` in the app).
//! * **Decimal:** the reference computes `Decimal(str(mag)).quantize(10^-places, HALF_UP)`
//!   -- a direct quantize, no multiply. The digit limit is on the result coefficient.
//!   This port matches that exactly.
//! * **No value ever overflows a fixed-width integer here.** The scaled product is kept as
//!   big-endian decimal digits (bounded: a finite f64 times `denom <= 1024` has at most
//!   ~312 digits), and whole/remainder parts come out of decimal long division by the
//!   small denominator -- never a `u128` fold (which would wrap or panic for a large
//!   value under a large context precision, e.g. `1e100` under `prec >= 40`);
//! * `decimal` formats NaN as `NaN`; infinities raise `InvalidOperation`;
//! * fractional and feet-and-inches raise `ValueError` for NaN ("cannot convert NaN to
//!   integer") and `InvalidOperation` for infinities;
//! * a value that rounds to zero keeps its sign (`-0.001` at 2 places is `-0.00`);
//! * mode names are `str.strip()`-ped (Unicode whitespace), lowercased, and `&` becomes `and`.
//!   Non-ASCII text can never match a mode name (the Kelvin sign is the only non-ASCII
//!   character whose lowercase is ASCII, and no mode name contains `k`; the generator asserts
//!   this). The Unicode whitespace table is generated by
//!   `spike/rust_ports_overnight/gen_py_unicode_tables.py --block unitformat`;
//!
//! Integration seam: the Python layer converts the value (bool and int become float;
