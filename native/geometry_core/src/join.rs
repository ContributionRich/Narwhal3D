    #[test]
    fn exact_join_tolerance_and_existing_solids() {
        let closed_face = join(&fixture(10), 1e-6).unwrap();
        let r = inspect(&closed_face);
        assert_eq!(
            (r.valid, r.airtight, r.face_count, r.torus_faces),
            (1, 1, 1, 1)
        );
        assert!((r.volume - 6. * std::f64::consts::PI.powi(2)).abs() < 1e-9);
        assert_eq!(stats(&closed_face)[..2], [1., 1.]);
        let b = fixture(6);
        let inside = join(&b, 1e-4).unwrap();
        let outside = join(&b, 1e-5).unwrap();
        assert_eq!(stats(&inside)[..2], [1., 0.]);
        assert_eq!(stats(&outside)[..2], [2., 0.]);
        assert!((stats(&inside)[2] - stats(&b)[2]).abs() < 1e-10);
        for kind in [3, 9] {
            let out = join(&fixture(kind), 1e-6).unwrap();
            assert_eq!(stats(&out)[..2], [2., 2.]);
        }
    }
    #[test]
    fn join_default_and_unit_scaled_tolerances_preserve_exact_geometry() {
        for (kind, tolerance, volume) in [
            (0, 0.02, 24.),
            (1, 0.02, 12. * std::f64::consts::PI),
            (13, 0.508, 24. * 25.4_f64.powi(3)),
        ] {
            let b = fixture(kind);
            let output = join(&b, tolerance)
                .unwrap_or_else(|status| panic!("fixture {kind} tolerance {tolerance}: {status}"));
            let r = inspect(&output);
            assert_eq!((r.valid, r.airtight), (1, 1));
            assert_eq!(r.face_count, if kind == 1 { 3 } else { 6 });
            assert!((r.volume - volume).abs() < volume * 1e-12);
            assert!((stats(&b)[2] - stats(&output)[2]).abs() < stats(&b)[2] * 1e-12);
        }
        for (kind, tolerance, groups) in [(11, 0.02, 1.), (12, 0.02, 2.)] {
            let b = fixture(kind);
            let output = join(&b, tolerance)
                .unwrap_or_else(|status| panic!("fixture {kind} tolerance {tolerance}: {status}"));
            assert_eq!(stats(&output)[..2], [groups, 0.], "fixture {kind}");
            assert!((stats(&b)[2] - stats(&output)[2]).abs() < 1e-12);
        }
    }
    #[test]
    fn join_feature_scale_and_numeric_overflow_refusals_are_not_clipped() {
        let b = fixture(0);
        assert_eq!(join(&fixture(17), 1e-6), Err(ERROR_POLICY_REFUSED));
        // Box shortest edge is 2: a tolerance above 2/4 is inadmissible.
        for tolerance in [0.5001, 1., 1e100] {
            assert_eq!(join(&b, tolerance), Err(ERROR_POLICY_REFUSED));
            let mut report = JoinReport {
                group_count: 99,
                ..Default::default()
            };
            let mut output = [0xa5; 128];
            assert_eq!(
                unsafe {
                    narwhal_geometry_core_join_mapped_v1(
                        b.as_ptr(),
                        b.len(),
                        tolerance,
                        output.as_mut_ptr(),
                        output.len(),
                        &mut report,
                    )
                },
                ERROR_POLICY_REFUSED
            );
            assert_eq!(report.group_count, 0);
            assert_eq!(output, [0xa5; 128]);
        }
        // Ordinary OCCT metadata is 1e-7, never silently raised to admit 1e-9.
        assert_eq!(join(&b, 1e-9), Err(ERROR_POLICY_REFUSED));
        // MEASURED: ShapeFix SetTolerance itself floors faces/edges/vertices at
        // 1e-7. An attempted 1e-9 fixture is NOT a qualified precise source.
        for kind in [14, 15, 16] {
            assert_eq!(join(&fixture(kind), 1e-9), Err(ERROR_POLICY_REFUSED));
        }
        for tolerance in [0., -1., 1e-10, f64::INFINITY, f64::NAN, f64::MAX, 1e155] {
            assert_eq!(join(&b, tolerance), Err(ERROR_INVALID_ARGUMENT));
            let mut report = JoinReport::default();
            let mut output = [0x5a; 128];
            assert_eq!(
                unsafe {
                    narwhal_geometry_core_join_mapped_v1(
                        b.as_ptr(),
                        b.len(),
                        tolerance,
                        output.as_mut_ptr(),
                        output.len(),
                        &mut report,
                    )
                },
                ERROR_INVALID_ARGUMENT
            );
            assert_eq!(report.group_count, 0);
            assert_eq!(output, [0x5a; 128]);
            assert_eq!(
                unsafe {
                    narwhal_geometry_core_verify_join_v1(
                        b.as_ptr(),
                        b.len(),
                        b.as_ptr(),
                        b.len(),
                        tolerance,
                    )
                },
                ERROR_INVALID_ARGUMENT as i32
            );
        }
    }
