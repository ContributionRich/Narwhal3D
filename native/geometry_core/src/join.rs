//! OURS: bounded exact sewing candidate, not general reference-application Join equivalence.
//! Input/output are BinTools compounds of groups; solids pass through unchanged.
use crate::*;

pub const CAPABILITY: u64 = 1 << 9;

// Join has no local-edit/document-unit ceiling. Squared-distance arithmetic must
// remain representable; actual geometric scale admission belongs to OCCT below.
fn join_tolerance_is_valid(tolerance: f64) -> bool {
    tolerance.is_finite() && tolerance >= 1e-9 && (tolerance * tolerance).is_finite()
}

extern "C" {
    fn narwhal_occt_adapter_join_exact(
        input: *const u8,
        length: usize,
        tolerance: f64,
        output: *mut u8,
        capacity: usize,
        required: *mut usize,
    ) -> i32;
}

/// Sew existing boundaries only. The caller supplies an already policy-qualified
/// sewing tolerance (the document's 2x policy belongs to the command layer).
/// Returns byte count, or an existing negative core error. Buffer queries return
/// the required count; errors never publish partial output.
/// # Safety
/// Spans must be live caller-owned allocations and must not overlap.
#[no_mangle]
pub unsafe extern "C" fn narwhal_geometry_core_join_exact_v1(
    input: *const u8,
    length: usize,
    tolerance: f64,
    output: *mut u8,
    capacity: usize,
) -> i64 {
    if length == 0 || length > MAX_BUFFER_BYTES || capacity > MAX_BUFFER_BYTES {
        return ERROR_LIMIT_EXCEEDED;
    }
    if !span_metadata_is_valid(input, length)
        || (capacity != 0 && !span_metadata_is_valid(output, capacity))
        || spans_overlap(input, length, output, capacity)
        || !join_tolerance_is_valid(tolerance)
    {
        return ERROR_INVALID_ARGUMENT;
    }
    catch_unwind(AssertUnwindSafe(|| {
        let mut required = 0;
        let status = unsafe {
            narwhal_occt_adapter_join_exact(
                input,
                length,
                tolerance,
                output,
                capacity,
                &mut required,
            )
        };
        if status == ADAPTER_OK || (status == ADAPTER_BUFFER_TOO_SMALL && capacity == 0) {
            if required > MAX_BUFFER_BYTES {
                ERROR_LIMIT_EXCEEDED
            } else {
                required as i64
            }
        } else if status == ADAPTER_BUFFER_TOO_SMALL {
            ERROR_BUFFER_TOO_SMALL
        } else {
            adapter_error(status)
        }
    }))
    .unwrap_or(ERROR_UNEXPECTED_FAILURE)
}

/// Stable input membership, generated by the native face-identity trace.
#[repr(C)]
#[derive(Clone, Debug, PartialEq)]
pub struct JoinReport {
    pub struct_size: u32,
    pub version: u32,
    pub status: i32,
    pub input_count: u32,
    pub group_count: u32,
    pub offsets: [u32; 257],
    pub members: [u32; 256],
    pub closed: [u32; 256],
}
impl Default for JoinReport {
    fn default() -> Self {
        Self {
            struct_size: size_of::<Self>() as u32,
            version: 1,
            status: 0,
            input_count: 0,
            group_count: 0,
            offsets: [0; 257],
            members: [0; 256],
            closed: [0; 256],
        }
    }
}
extern "C" {
    fn narwhal_occt_adapter_join_mapped(
        input: *const u8,
        length: usize,
        tolerance: f64,
        output: *mut u8,
        capacity: usize,
        required: *mut usize,
        report: *mut JoinReport,
    ) -> i32;
    fn narwhal_occt_adapter_verify_join(
        input: *const u8,
        length: usize,
        target: *const u8,
        target_length: usize,
        tolerance: f64,
    ) -> i32;
}
/// Exact Join with native source membership. Report is reset on every refusal.
/// # Safety
/// All spans must be valid, live, and disjoint, including the report.
#[no_mangle]
pub unsafe extern "C" fn narwhal_geometry_core_join_mapped_v1(
    input: *const u8,
    length: usize,
    tolerance: f64,
    output: *mut u8,
    capacity: usize,
    report: *mut JoinReport,
) -> i64 {
    if !span_metadata_is_valid(report, 1)
        || spans_overlap(input, length, report.cast(), size_of::<JoinReport>())
        || spans_overlap(output, capacity, report.cast(), size_of::<JoinReport>())
    {
        return ERROR_INVALID_ARGUMENT;
    }
    let mut info = JoinReport::default();
    let result = catch_unwind(AssertUnwindSafe(|| {
        if length == 0 || length > MAX_BUFFER_BYTES || capacity > MAX_BUFFER_BYTES {
            return ERROR_LIMIT_EXCEEDED;
        }
        if !span_metadata_is_valid(input, length)
            || (capacity != 0 && !span_metadata_is_valid(output, capacity))
            || spans_overlap(input, length, output, capacity)
            || !join_tolerance_is_valid(tolerance)
        {
            return ERROR_INVALID_ARGUMENT;
        }
        let mut required = 0;
        let status = unsafe {
            narwhal_occt_adapter_join_mapped(
                input,
                length,
                tolerance,
                output,
                capacity,
                &mut required,
                &mut info,
            )
        };
        if status == ADAPTER_OK || (status == ADAPTER_BUFFER_TOO_SMALL && capacity == 0) {
            if required > MAX_BUFFER_BYTES {
                ERROR_LIMIT_EXCEEDED
            } else {
                required as i64
            }
        } else if status == ADAPTER_BUFFER_TOO_SMALL {
            ERROR_BUFFER_TOO_SMALL
        } else {
            adapter_error(status)
        }
    }))
    .unwrap_or(ERROR_UNEXPECTED_FAILURE);
    if result < 0 {
        info = JoinReport {
            status: result as i32,
            ..Default::default()
        };
    }
    unsafe { ptr::write(report, info) };
    result
}
/// Verify that an exact frozen single result is bound to its rebuilt operands.
/// # Safety
/// Both input spans must remain live and readable for their declared lengths.
#[no_mangle]
pub unsafe extern "C" fn narwhal_geometry_core_verify_join_v1(
    input: *const u8,
    length: usize,
    target: *const u8,
    target_length: usize,
    tolerance: f64,
) -> i32 {
    if length == 0
        || target_length == 0
        || length > MAX_BUFFER_BYTES
        || target_length > MAX_BUFFER_BYTES
    {
        return ERROR_LIMIT_EXCEEDED as i32;
    }
    if !span_metadata_is_valid(input, length)
        || !span_metadata_is_valid(target, target_length)
        || !join_tolerance_is_valid(tolerance)
    {
        return ERROR_INVALID_ARGUMENT as i32;
    }
    catch_unwind(AssertUnwindSafe(|| unsafe {
        narwhal_occt_adapter_verify_join(input, length, target, target_length, tolerance)
    }))
    .unwrap_or(ERROR_UNEXPECTED_FAILURE as i32)
}

