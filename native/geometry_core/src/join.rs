    #[test]
    fn exact_join_box_cylinder_open_and_disconnected() {
        for (kind, faces, planes, cylinders, volume) in
            [(0, 6, 6, 0, 24.), (1, 3, 2, 1, 12. * std::f64::consts::PI)]
        {
            let source = fixture(kind);
            let before = source.clone();
            let out = join(&source, 1e-6).unwrap();
            let r = inspect(&out);
            assert_eq!(source, before);
            assert_eq!(stats(&out)[..2], [1., 1.]);
            assert!((stats(&out)[2] - stats(&source)[2]).abs() < 1e-10);
            assert_eq!(
                (
                    r.valid,
                    r.airtight,
                    r.face_count,
                    r.plane_faces,
                    r.cylinder_faces
                ),
                (1, 1, faces, planes, cylinders)
            );
            assert!((r.volume - volume).abs() < 1e-9);
        }
        let open = inspect(&join(&fixture(2), 1e-6).unwrap());
        assert_eq!((open.valid, open.airtight, open.face_count), (1, 0, 2));
        let groups = inspect(&join(&fixture(3), 1e-6).unwrap());
        assert_eq!((groups.valid, groups.face_count), (1, 12));
    }
