//! Regenerate/verify the ordinal map from the pinned openNURBS source, not Unicode casing.
//! Usage: generate_ordinal SOURCE_CPP SCRATCH_DIR OUTPUT_RS
//! Compile/run under the shared heavy-build lock. No vendor source is modified.
use std::{env, fs, path::Path, process::Command};

fn main() {
    let args: Vec<String> = env::args().collect();
    assert_eq!(args.len(), 4, "SOURCE_CPP SCRATCH_DIR OUTPUT_RS");
    let hash = Command::new("sha256sum").arg(&args[1]).output().unwrap();
    assert!(hash.status.success());
    assert!(
        String::from_utf8(hash.stdout)
            .unwrap()
            .starts_with("a34fea6150cd2830925c159bc87c42da54ded0c6093cb2e5b8a0775b627c2cbe "),
        "Pinned openNURBS source changed; review before regenerating"
    );
    let source = fs::read_to_string(&args[1]).unwrap();
    let map = &source[source
        .find("static ON__UINT32 MapCodePointOrdinal(")
        .unwrap()
        ..source
            .find("ON__UINT32 ON_UnicodeMapCodePointOrdinal(")
            .unwrap()];
    let ordinal = &source[source
        .find("static unsigned int OrdinalUnsignedToIgnoreCase(")
        .unwrap()
        ..source
            .find("static unsigned int OrdinalUTF8ToIgnoreCase(")
            .unwrap()];
    let scratch = Path::new(&args[2]);
    fs::create_dir_all(scratch).unwrap();
    let cpp = scratch.join("ordinal_reference.cpp");
    let exe = scratch.join("ordinal_reference");
    fs::write(
        &cpp,
        format!(
            r#"// Extracted unmodified functions from pinned openNURBS; see generated Rust notice.
#include <cstdint>
#include <cstdio>
using ON__UINT32 = uint32_t;
enum class ON_StringMapOrdinalType {{ Identity, UpperOrdinal, LowerOrdinal, MinimumOrdinal }};
{map}
{ordinal}
int main() {{
  for (uint32_t c = 0; c <= 0x10ffff; ++c) {{
    if (c >= 0xd800 && c <= 0xdfff) continue;
    auto mapped = OrdinalUnsignedToIgnoreCase(c, 0xffffffff);
    if (c <= 0xffff) {{
      if (mapped != OrdinalUnsignedToIgnoreCase(c, 0xffff)) return 2;
    }} else {{
      auto hi = 0xd800 + ((c - 0x10000) >> 10);
      auto lo = 0xdc00 + ((c - 0x10000) & 0x3ff);
      if (mapped != c || OrdinalUnsignedToIgnoreCase(hi, 0xffff) != hi
          || OrdinalUnsignedToIgnoreCase(lo, 0xffff) != lo) return 3;
    }}
    if (mapped != c) std::printf("    (0x%X, 0x%X),\n", c, mapped);
  }}
}}
"#
        ),
    )
    .unwrap();
    assert!(Command::new("g++")
        .args(["-std=c++11", "-O0"])
        .arg(&cpp)
        .arg("-o")
        .arg(&exe)
        .status()
        .unwrap()
        .success());
    let output = Command::new(&exe).output().unwrap();
    assert!(output.status.success(), "UTF16/UTF32 mapping mismatch");
    let pairs = String::from_utf8(output.stdout).unwrap();
    let generated = format!(
        "// @generated by generate_ordinal.rs from pinned openNURBS. Do not hand edit.\n\
// DERIVED: one pass of OrdinalUnsignedToIgnoreCase(c, 0xffffffff).\n\
// Source SHA256: a34fea6150cd2830925c159bc87c42da54ded0c6093cb2e5b8a0775b627c2cbe\n\
// Copyright (c) 1993-2022 Robert McNeel & Associates. All rights reserved.\n\
// OpenNURBS, Rhinoceros, and Rhino3D are registered trademarks of Robert\n\
// McNeel & Associates.\n\
// THIS SOFTWARE IS PROVIDED \"AS IS\" WITHOUT EXPRESS OR IMPLIED WARRANTY.\n\
// ALL IMPLIED WARRANTIES OF FITNESS FOR ANY PARTICULAR PURPOSE AND OF\n\
// MERCHANTABILITY ARE HEREBY DISCLAIMED.\n\
// For complete openNURBS copyright information see <http://www.opennurbs.org>.\n\
// This derived Rust table is not original openNURBS source. See OPENNURBS_LICENSE.\n\
pub(crate) const ORDINAL_MAP: &[(u32, u32)] = &[\n{pairs}];\n"
    );
    fs::write(&args[3], generated).unwrap();
    println!(
        "Verified 1,112,064 Unicode scalars, UTF16/UTF32 equivalence; {} nonidentity mappings",
        pairs.lines().count()
    );
}
