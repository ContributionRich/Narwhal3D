"""Generate the Python-Unicode tables embedded in the RUST-PORTS-01 Rust modules.

Rust's std does not expose CPython's text semantics, and its Unicode version differs from
the reference interpreter, so the ports carry these tables as data, derived from CPython
3.13 (Unicode 15.1.0):

* ``printwidths`` block -> native/pure_core/src/printwidths.rs
    isspace (non-ASCII), isprintable complement, decimal-digit runs.
* ``command_history`` block -> native/pure_core/src/command_history.rs
    full ``str.lower()`` mappings, Cased and Case_Ignorable ranges (the inputs to CPython's
    final-sigma rule).

Usage (the splice replaces only the marked block):

    tools/blender-patched/5.2/python/bin/python3.13 -B \
        spike/rust_ports_overnight/gen_py_unicode_tables.py --block printwidths \
        --splice native/pure_core/src/printwidths.rs
    tools/blender-patched/5.2/python/bin/python3.13 -B \
        spike/rust_ports_overnight/gen_py_unicode_tables.py --block command_history \
        --splice native/pure_core/src/command_history.rs

``--check FILE`` exits non-zero when FILE does not contain a fresh regeneration of the block.
"""
import argparse
import sys
import unicodedata

MARKERS = {
    "printwidths": ("// BEGIN GENERATED PY UNICODE TABLES", "// END GENERATED PY UNICODE TABLES"),
    "command_history": ("// BEGIN GENERATED PY CASE TABLES", "// END GENERATED PY CASE TABLES"),
    "unitformat": ("// BEGIN GENERATED PY SPACE TABLE", "// END GENERATED PY SPACE TABLE"),
    "casefold": ("// BEGIN GENERATED PY CASEFOLD TABLE", "// END GENERATED PY CASEFOLD TABLE"),
}


def _runs(pairs):
    """Merge sorted (codepoint, key) pairs into [lo, hi, key] runs of consecutive
    codepoints sharing a key."""
    out = []
    for cp, key in pairs:
        if out and out[-1][1] == cp - 1 and out[-1][2] == key:
            out[-1][1] = cp
        else:
            out.append([cp, cp, key])
    return out


def _fmt_pairs(name, doc, rows):
    """One entry per line: this is rustfmt's layout, so editor format-on-save leaves the
    block unchanged and --check stays meaningful."""
    lines = [f"/// {doc}", f"const {name}: &[(u32, u32)] = &["]
    lines.extend(f"    (0x{lo:x}, 0x{hi:x})," for lo, hi in rows)
    lines.append("];")
    return "\n".join(lines)


def _is_surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def build_printwidths_block():
    space = []
    nonprint = []
    decimal = []
    for cp in range(0x110000):
        ch = chr(cp)
        if ch.isspace() and cp >= 0x80:
            space.append((cp, 0))
        if not ch.isprintable():
            nonprint.append((cp, 0))
        d = unicodedata.decimal(ch, -1)
        if d >= 0:
            # Key = (value - codepoint) mod 10: constant along a digit run.
            decimal.append((cp, (d - cp) % 10))
    space_rows = [(lo, hi) for lo, hi, _ in _runs(space)]
    nonprint_rows = [(lo, hi) for lo, hi, _ in _runs(nonprint)]
    dec_rows = [(lo, hi, key) for lo, hi, key in _runs(decimal)]

    parts = [
        MARKERS["printwidths"][0],
        f"// Generated by spike/rust_ports_overnight/gen_py_unicode_tables.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).",
        "// Do not edit by hand: regenerate and re-splice.",
        _fmt_pairs(
            "PY_SPACE_NON_ASCII",
            "Non-ASCII code points for which Python's str.isspace() is true.",
            space_rows),
        "",
        _fmt_pairs(
            "PY_NONPRINTABLE",
            "Code points for which Python's str.isprintable() is false (includes ASCII "
            "controls, DEL, Zs other than U+0020, Cf, Co, Cn and surrogates).",
            nonprint_rows),
        "",
        "/// (lo, hi, key): for cp in lo..=hi, the decimal value is (cp + key) % 10.",
        "const PY_DECIMAL_RUNS: &[(u32, u32, u32)] = &[",
    ]
    parts.extend(f"    (0x{lo:x}, 0x{hi:x}, {key})," for lo, hi, key in dec_rows)
    parts.append("];")
    parts.append(MARKERS["printwidths"][1])
    return "\n".join(parts) + "\n"


def _cased(ch):
    # Unicode Cased = Lowercase + Uppercase + Lt. CPython's islower/isupper implement the
    # Lowercase/Uppercase derived properties (including Other_Lowercase/Other_Uppercase).
    return ch.islower() or ch.isupper() or unicodedata.category(ch) == "Lt"


def _case_ignorable_by_probe(ch):
    """Case_Ignorable as CPython's ``str.lower()`` applies it in the final-sigma rule.

    ``unicodedata`` does not expose the property, so it is measured through the same
    rule. Two probes are needed because a cased ``ch`` is always final in ``"A"+ch+"Σ"``:
    * uncased ch: "A"+ch+"Σ" ends in ς exactly when ch is ignorable (the scan skips it
      to reach the cased A);
    * cased ch: "1"+ch+"Σ" ends in ς exactly when ch is NOT ignorable (ch itself is the
      cased character found by the backward scan). '1' is neither cased nor ignorable."""
    if _cased(ch):
        return not ("1" + ch + "\u03a3").lower().endswith("\u03c2")
    return ("A" + ch + "\u03a3").lower().endswith("\u03c2")


def build_command_history_block():
    # The probes rely on '1' being neither cased nor case-ignorable; check that first.
    assert ("A1\u03a3").lower() == "a1\u03c3"
    lower_rows = []
    cased_pairs = []
    ignorable_pairs = []
    for cp in range(0x110000):
        if _is_surrogate(cp):
            continue
        ch = chr(cp)
        mapped = ch.lower()
        if mapped != ch:
            lower_rows.append((cp, [ord(c) for c in mapped]))
        if _cased(ch):
            cased_pairs.append((cp, 0))
        if _case_ignorable_by_probe(ch):
            ignorable_pairs.append((cp, 0))
    cased_rows = [(lo, hi) for lo, hi, _ in _runs(cased_pairs)]
    ignorable_rows = [(lo, hi) for lo, hi, _ in _runs(ignorable_pairs)]

    parts = [
        MARKERS["command_history"][0],
        f"// Generated by spike/rust_ports_overnight/gen_py_unicode_tables.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).",
        "// Do not edit by hand: regenerate and re-splice.",
        "/// Full `str.lower()` mapping (cp, mapped code points) for every non-sigma code point",
        "/// that maps to something other than itself. U+03A3 is listed for documentation; the",
        "/// port resolves it with the final-sigma rule instead.",
        "const PY_LOWER_FULL: &[(u32, &[u32])] = &[",
    ]
    parts.extend(
        f"    (0x{cp:x}, &[{', '.join(f'0x{m:x}' for m in mapped)}])," for cp, mapped in lower_rows)
    parts.append("];")
    parts.append("")
    parts.append(_fmt_pairs(
        "PY_CASED",
        "Code points for which CPython's cased test (Cased property) is true.",
        cased_rows))
    parts.append("")
    parts.append(_fmt_pairs(
        "PY_CASE_IGNORABLE",
        "Case-ignorable code points as CPython's final-sigma rule uses them (cased ones included).",
        ignorable_rows))
    parts.append(MARKERS["command_history"][1])
    return "\n".join(parts) + "\n"


def build_unitformat_block():
    """unitformat matches normalized mode names after str.strip() and str.lower().

    Only Unicode whitespace is needed. The lowercase property it relies on is asserted here:
    the single non-ASCII code point whose lowercase is ASCII must be U+212A (KELVIN SIGN ->
    'k'), and no mode name contains 'k', so non-ASCII text can never match a mode."""
    space = []
    ascii_lowering = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        if ch.isspace() and cp >= 0x80:
            space.append((cp, 0))
        if cp >= 0x80 and ch.lower().isascii():
            ascii_lowering.append(cp)
    assert ascii_lowering == [0x212A], [hex(c) for c in ascii_lowering]
    for name in ("decimal", "fractional", "fraction", "feet and inches", "feet_inches", "feet-inch"):
        assert "k" not in name
    space_rows = [(lo, hi) for lo, hi, _ in _runs(space)]
    parts = [
        MARKERS["unitformat"][0],
        f"// Generated by spike/rust_ports_overnight/gen_py_unicode_tables.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).",
        "// Do not edit by hand: regenerate and re-splice.",
        _fmt_pairs(
            "PY_SPACE_NON_ASCII",
            "Non-ASCII code points for which Python's str.isspace() is true.",
            space_rows),
        MARKERS["unitformat"][1],
    ]
    return "\n".join(parts) + "\n"


def build_casefold_block():
    """Full str.casefold() mappings (CPython 3.13, Unicode 15.1), sparse: only code points whose
    casefold differs from themselves. Context-free per character, as CPython applies it."""
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        folded = ch.casefold()
        if folded != ch:
            rows.append((cp, [ord(c) for c in folded]))
    parts = [
        MARKERS["casefold"][0],
        f"// Generated by spike/rust_ports_overnight/gen_py_unicode_tables.py from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).",
        "// Do not edit by hand: regenerate and re-splice.",
        "/// Full `str.casefold()` mapping (cp, folded code points) for every code point whose",
        "/// casefold differs from itself, sorted by cp.",
        "const PY_CASEFOLD_FULL: &[(u32, &[u32])] = &[",
    ]
    parts.extend(
        f"    (0x{cp:x}, &[{', '.join(f'0x{m:x}' for m in mapped)}])," for cp, mapped in rows)
    parts.append("];")
    parts.append(MARKERS["casefold"][1])
    return "\n".join(parts) + "\n"


BUILDERS = {
    "printwidths": build_printwidths_block,
    "command_history": build_command_history_block,
    "unitformat": build_unitformat_block,
    "casefold": build_casefold_block,
}


def splice(path, block, block_name):
    begin, end = MARKERS[block_name]
    with open(path, "r", encoding="utf-8") as fh:
        text = fh.read()
    start = text.index(begin)
    stop = text.index(end) + len(end) + 1
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text[:start] + block + text[stop:])


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--block", choices=sorted(BUILDERS), required=True)
    ap.add_argument("--splice", metavar="FILE")
    ap.add_argument("--check", metavar="FILE")
    ap.add_argument("--print", action="store_true")
    args = ap.parse_args(argv)
    block = BUILDERS[args.block]()
    if args.splice:
        splice(args.splice, block, args.block)
        print(f"spliced {len(block)} bytes ({args.block}) into {args.splice}")
    if args.check:
        with open(args.check, "r", encoding="utf-8") as fh:
            text = fh.read()
        ok = block in text
        print("CHECK OK" if ok else "CHECK FAILED: embedded tables differ from regeneration")
        return 0 if ok else 1
    if args.print or not (args.splice or args.check):
        sys.stdout.write(block)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
